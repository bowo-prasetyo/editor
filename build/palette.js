// Draws docs/palette.svg, the swatches in docs/brand.md, from the palette at
// the top of src/style.css, so the picture can't drift from the real colours.
// Run it after changing the palette: `npm run palette`.
// test/palette.test.js fails if docs/palette.svg is out of date.
import { readFileSync, writeFileSync } from 'node:fs'

const root = new URL('../', import.meta.url)

// The tokens shown, in order, with what each is for.
export const SWATCHES = [
  ['bg', 'Page'],
  ['panel', 'Panels, bars'],
  ['border', 'Borders'],
  ['fg', 'Text'],
  ['muted', 'Secondary text'],
  ['accent', 'Links, focus, cursor'],
  ['accent-fill', 'Primary buttons'],
  ['brass', 'Notice, nothing lost'],
  ['highlight', 'Brass backgrounds'],
  ['danger', 'Real problems'],
  ['success', 'Added'],
]

// The custom properties of the first CSS block that starts with `opening`.
export function cssBlock(css, opening) {
  const start = css.indexOf(opening)
  if (start < 0) throw new Error(`No block ${opening}`)
  let depth = 0
  let i = css.indexOf('{', start)
  const from = i
  for (; i < css.length; i++) {
    if (css[i] === '{') depth++
    else if (css[i] === '}' && --depth === 0) break
  }
  const vars = {}
  for (const [, name, value] of css.slice(from, i).matchAll(/--([\w-]+):\s*([^;]+);/g)) vars[name] = value.trim()
  return vars
}

export function paletteThemes(css) {
  const light = cssBlock(css, ':root {')
  return { Light: light, Dark: { ...light, ...cssBlock(css, ":root:not([data-theme='light'])") } }
}

const ROW = 40
const TOP = 64
const PANEL_W = 420

export function paletteSvg(css) {
  const themes = Object.entries(paletteThemes(css))
  const height = TOP + SWATCHES.length * ROW + 16
  const panels = themes.map(([name, t], i) => {
    const x = i * (PANEL_W + 20)
    const rows = SWATCHES.map(([token, use], r) => {
      const y = TOP + r * ROW
      return [
        `    <rect x="20" y="${y}" width="28" height="28" rx="7" fill="${t[token]}" stroke="${t.border}"/>`,
        `    <text x="62" y="${y + 13}" fill="${t.fg}" font-size="14" font-family="ui-monospace, SFMono-Regular, Menlo, Consolas, monospace">--${token}</text>`,
        `    <text x="62" y="${y + 29}" fill="${t.muted}" font-size="12">${use}</text>`,
        `    <text x="${PANEL_W - 20}" y="${y + 19}" fill="${t.muted}" font-size="13" text-anchor="end" font-family="ui-monospace, SFMono-Regular, Menlo, Consolas, monospace">${t[token]}</text>`,
      ].join('\n')
    })
    return [
      `  <g transform="translate(${x} 0)">`,
      `    <rect width="${PANEL_W}" height="${height}" rx="14" fill="${t.bg}" stroke="${t.border}"/>`,
      `    <rect x="1" y="1" width="${PANEL_W - 2}" height="44" rx="13" fill="${t.panel}"/>`,
      `    <rect x="1" y="32" width="${PANEL_W - 2}" height="13" fill="${t.panel}"/>`,
      `    <text x="20" y="29" fill="${t.fg}" font-size="15" font-weight="600">${name}</text>`,
      ...rows,
      '  </g>',
    ].join('\n')
  })
  const width = themes.length * PANEL_W + (themes.length - 1) * 20
  return [
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" font-family="system-ui, -apple-system, Segoe UI, sans-serif" role="img" aria-label="The Plumb palette, light and dark">`,
    '  <!-- Generated by build/palette.js from src/style.css. Do not edit by hand: run npm run palette. -->',
    ...panels,
    '</svg>',
    '',
  ].join('\n')
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const css = readFileSync(new URL('src/style.css', root), 'utf8')
  writeFileSync(new URL('docs/palette.svg', root), paletteSvg(css))
}
